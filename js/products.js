/* Хелперы каталога */
function findProduct(id) {
  return PRODUCTS.find(p => p.id === id) || null;
}

function productsByAge(chipId) {
  if (!chipId) return PRODUCTS;
  const [min, max] = chipId.split('-').map(Number);
  return PRODUCTS.filter(p => p.ages[0] <= max && p.ages[1] >= min);
}

function productsByType(typeId) {
  if (!typeId) return PRODUCTS;
  return PRODUCTS.filter(p => p.type === typeId);
}
